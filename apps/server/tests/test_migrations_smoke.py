    """Every downgrade() must run cleanly. Some are autogenerated ('please adjust!'), and a broken one
    (wrong constraint name, missing table) would otherwise only surface at a real production rollback —
    the worst possible moment. Walk the whole chain down to base and back up to head (6.152)."""
    smoke_url = migrated_engine.url.render_as_string(hide_password=False)
