def test_rename_frp_provision_tokens_preserves_rows(pg_engine, monkeypatch):
    # 4.62: op.rename_table must carry the rows over — the old create_table + drop_table silently
    # destroyed every pending provision token. Migrate to just before the rename, plant a token,
    # apply the rename, and assert the token survived under the new table name.
    admin_url = pg_engine.url
    dbname = f"alembic_rename_{uuid.uuid4().hex[:8]}"
    admin_engine = create_engine(admin_url, isolation_level="AUTOCOMMIT")
    with admin_engine.connect() as conn:
        conn.execute(text(f'CREATE DATABASE "{dbname}"'))
    smoke_url = admin_url.set(database=dbname).render_as_string(hide_password=False)
    monkeypatch.setattr(app_config, "DATABASE_URL", smoke_url)
    cfg = Config(str(SERVER_DIR / "alembic.ini"))
    cfg.set_main_option("script_location", str(SERVER_DIR / "alembic"))
    engine = create_engine(smoke_url)
    try:
        command.upgrade(cfg, "1d8276d3aa26")  # the down_revision, just before the rename
        with engine.begin() as conn:
            conn.execute(text("INSERT INTO servers (id, name, hostname) VALUES ('s1', 'S', 'h')"))
            conn.execute(
                text(
                    "INSERT INTO frp_provision_tokens (id, server_id, hashed_token, expires_at)"
                    " VALUES ('t1', 's1', 'hash', '2099-01-01 00:00:00')"
                )
            )
        command.upgrade(cfg, "0494a8f377ef")  # the rename — must preserve the row
        with engine.connect() as conn:
            row = conn.execute(
                text("SELECT server_id, hashed_token FROM provision_tokens WHERE id = 't1'")
            ).first()
        assert row is not None, "das Provision-Token muss das Rename ueberleben"
        assert row[0] == "s1" and row[1] == "hash"
    finally:
        engine.dispose()
        _drop_database(admin_engine, dbname)
        admin_engine.dispose()


def test_uniq_visitor_port_frees_younger_duplicate_instead_of_deleting(pg_engine, monkeypatch):
    # 4.64: pre-existing STCP visitor_port duplicates (a real race artifact) must be defused
    # before CREATE UNIQUE INDEX — per port the OLDEST tunnel keeps it, younger ones lose it to
    # NULL. Unlike the content-identical template-assignment dedupe the ROW is preserved (a
    # distinct tunnel), only its port is freed. Migrate to just before the index, plant two stcp
    # tunnels sharing a port, apply the migration.
    admin_url = pg_engine.url
    dbname = f"alembic_vport_{uuid.uuid4().hex[:8]}"
    admin_engine = create_engine(admin_url, isolation_level="AUTOCOMMIT")
    with admin_engine.connect() as conn:
        conn.execute(text(f'CREATE DATABASE "{dbname}"'))
    smoke_url = admin_url.set(database=dbname).render_as_string(hide_password=False)
    monkeypatch.setattr(app_config, "DATABASE_URL", smoke_url)
    cfg = Config(str(SERVER_DIR / "alembic.ini"))
    cfg.set_main_option("script_location", str(SERVER_DIR / "alembic"))
    engine = create_engine(smoke_url)
    try:
        command.upgrade(cfg, "e7b3c1a9d2f4")  # the down_revision, just before the unique index
        with engine.begin() as conn:
            conn.execute(text("INSERT INTO servers (id, name, hostname) VALUES ('s1', 'S', 'h')"))
            conn.execute(
                text(
                    "INSERT INTO frp_server_config (id, name, server_addr, auth_token)"
                    " VALUES ('c1', 'C', 'frps', 'tok')"
                )
            )
            for tid, created in (("t_old", "2026-01-01"), ("t_new", "2026-02-01")):
                conn.execute(
                    text(
                        "INSERT INTO frp_tunnels (id, server_id, frp_config_id, name, tunnel_type,"
                        " protocol, local_port, visitor_port, created_at)"
                        f" VALUES ('{tid}', 's1', 'c1', '{tid}', 'stcp', 'ssh', 22, 7000,"
                        f" '{created} 00:00:00')"
                    )
                )
        command.upgrade(cfg, "f1a2b3c4d5e6")  # dedupe (NULL the younger) + index — must not crash
        with engine.connect() as conn:
            rows = dict(
                conn.execute(text("SELECT id, visitor_port FROM frp_tunnels ORDER BY id")).all()
            )
        assert rows["t_old"] == 7000, "der aeltere Tunnel behaelt seinen visitor_port"
        assert rows["t_new"] is None, "der juengere verliert den Port (NULL), bleibt aber erhalten"
    finally:
        engine.dispose()
        _drop_database(admin_engine, dbname)
        admin_engine.dispose()


def test_add_server_id_backfill_skips_ambiguous_names(pg_engine, monkeypatch):
    # 4.63: the agent-key backfill must bind only unambiguous server names. Two servers named
    # "dup" → agent-dup stays NULL (fail-closed, agent re-provisions) rather than binding to a
    # random one; a unique "uniq" → agent-uniq is bound. Migrate to just before server_id is
    # added, plant the rows, apply the migration.
    admin_url = pg_engine.url
    dbname = f"alembic_apikey_{uuid.uuid4().hex[:8]}"
    admin_engine = create_engine(admin_url, isolation_level="AUTOCOMMIT")
    with admin_engine.connect() as conn:
        conn.execute(text(f'CREATE DATABASE "{dbname}"'))
    smoke_url = admin_url.set(database=dbname).render_as_string(hide_password=False)
    monkeypatch.setattr(app_config, "DATABASE_URL", smoke_url)
    cfg = Config(str(SERVER_DIR / "alembic.ini"))
    cfg.set_main_option("script_location", str(SERVER_DIR / "alembic"))
    engine = create_engine(smoke_url)
    try:
        command.upgrade(cfg, "0494a8f377ef")  # the down_revision, before api_keys.server_id
        with engine.begin() as conn:
            conn.execute(
                text(
                    "INSERT INTO servers (id, name, hostname) VALUES"
                    " ('s1', 'dup', 'h1'), ('s2', 'dup', 'h2'), ('s3', 'uniq', 'h3')"
                )
            )
            conn.execute(
                text(
                    "INSERT INTO api_keys (name, hashed_key, permission) VALUES"
                    " ('agent-dup', 'h_dup', 'read'), ('agent-uniq', 'h_uniq', 'read')"
                )
            )
        command.upgrade(cfg, "c3a7e1f50b2d")  # adds server_id + backfills
        with engine.connect() as conn:
            rows = dict(
                conn.execute(text("SELECT name, server_id FROM api_keys ORDER BY name")).all()
            )
        assert rows["agent-uniq"] == "s3", "eindeutiger Name wird gebunden"
        assert rows["agent-dup"] is None, "mehrdeutiger Name bleibt NULL (fail-closed)"
    finally:
        engine.dispose()
        _drop_database(admin_engine, dbname)
        admin_engine.dispose()


def test_fill_empty_stcp_secrets_gives_each_its_own(pg_engine, monkeypatch):
    # Before the data migration an stcp tunnel could hold secret_key NULL or ''; afterwards each
    # of them has its own secret, while a set secret and an https tunnel stay as they were.
    admin_url = pg_engine.url
    dbname = f"alembic_stcpsecret_{uuid.uuid4().hex[:8]}"
    admin_engine = create_engine(admin_url, isolation_level="AUTOCOMMIT")
    with admin_engine.connect() as conn:
        conn.execute(text(f'CREATE DATABASE "{dbname}"'))
    smoke_url = admin_url.set(database=dbname).render_as_string(hide_password=False)
    monkeypatch.setattr(app_config, "DATABASE_URL", smoke_url)
    cfg = Config(str(SERVER_DIR / "alembic.ini"))
    cfg.set_main_option("script_location", str(SERVER_DIR / "alembic"))
    engine = create_engine(smoke_url)
    try:
        command.upgrade(cfg, "e5f7a1b3c9d0")  # the down_revision, just before the data migration
        with engine.begin() as conn:
            conn.execute(text("INSERT INTO servers (id, name, hostname) VALUES ('s1', 'S', 'h')"))
            conn.execute(
                text(
                    "INSERT INTO frp_server_config (id, name, server_addr, auth_token)"
                    " VALUES ('c1', 'C', 'frps', 'tok')"
                )
            )
            for tid, ttype, port, secret in (
                ("t_null", "stcp", 7001, None),
                ("t_empty", "stcp", 7002, ""),
                ("t_set", "stcp", 7003, "kept-secret-0123456789"),
                ("t_web", "https", None, None),
            ):
                conn.execute(
                    text(
                        "INSERT INTO frp_tunnels (id, server_id, frp_config_id, name, tunnel_type,"
                        " protocol, local_port, visitor_port, secret_key)"
                        " VALUES (:id, 's1', 'c1', :id, :type, 'ssh', 22, :port, :secret)"
                    ),
                    {"id": tid, "type": ttype, "port": port, "secret": secret},
                )
        command.upgrade(cfg, "8bdf9641a51f")
        with engine.connect() as conn:
            rows = dict(conn.execute(text("SELECT id, secret_key FROM frp_tunnels")).all())
        assert rows["t_null"] and len(rows["t_null"]) >= 32
        assert rows["t_empty"] and len(rows["t_empty"]) >= 32
        assert rows["t_null"] != rows["t_empty"], "jede Zeile bekommt ein eigenes Secret"
        assert rows["t_set"] == "kept-secret-0123456789"
        assert rows["t_web"] is None
    finally:
        engine.dispose()
        _drop_database(admin_engine, dbname)
        admin_engine.dispose()


def test_certificate_register_installs_its_time_and_goes_on_downgrade(pg_engine, monkeypatch):
    # R-0224: the revision writes the one state row whose install time starts the transition,
    # records no certificate, and its downgrade removes all three tables.
    # libpq sends PGTZ on every new connection, Alembic's included: in a session at UTC+14
    # without DST a now() default lands 14 h beside timezone('UTC', now()). In a UTC session
    # (the CI database) the two are the same and the deviation check below proves nothing.
    monkeypatch.setenv("PGTZ", "Pacific/Kiritimati")
    admin_url = pg_engine.url
    dbname = f"alembic_certreg_{uuid.uuid4().hex[:8]}"
    admin_engine = create_engine(admin_url, isolation_level="AUTOCOMMIT")
    with admin_engine.connect() as conn:
        conn.execute(text(f'CREATE DATABASE "{dbname}"'))
    smoke_url = admin_url.set(database=dbname).render_as_string(hide_password=False)
    monkeypatch.setattr(app_config, "DATABASE_URL", smoke_url)
    cfg = Config(str(SERVER_DIR / "alembic.ini"))
    cfg.set_main_option("script_location", str(SERVER_DIR / "alembic"))
    engine = create_engine(smoke_url)
    tables = ("device_lines", "issued_certificates", "certificate_register_state")
    try:
        command.upgrade(cfg, "3f9c2a7e5b1d")
        with engine.connect() as conn:
            zone = conn.execute(text("SHOW TimeZone")).scalar_one()
            state = conn.execute(
                text(
                    "SELECT id, timezone('UTC', now()) - installed_at FROM certificate_register_state"
                )
            ).all()
            certificates = conn.execute(text("SELECT count(*) FROM issued_certificates")).scalar()
        assert zone == "Pacific/Kiritimati", "die Pruefverbindung lief nicht fern von UTC"
        assert [row[0] for row in state] == [1], "genau eine Zustandszeile"
        # Naive UTC like every other default (F7): a session-timezone default would be hours off.
        assert abs(state[0][1].total_seconds()) < 300
        assert certificates == 0, "nichts wird rueckerfasst"

        command.downgrade(cfg, "8bdf9641a51f")
        with engine.connect() as conn:
            left = conn.execute(
                text("SELECT tablename FROM pg_tables WHERE tablename = ANY(:names)"),
                {"names": list(tables)},
            ).all()
        assert left == []
    finally:
        engine.dispose()
        _drop_database(admin_engine, dbname)
        admin_engine.dispose()


def test_outbox_text_columns_come_and_go(pg_engine, monkeypatch):
    # monitoring-alert-quality T18: the revision gives outbox entries a title and body of their
    # own, nullable, so an entry queued before keeps NULL and with it the notification's text.
    # Its downgrade drops both columns and keeps every entry, but a pending one with a text of
    # its own ends failed: sent later with the notification's text it would name servers its
    # channel was never meant to carry.
    admin_url = pg_engine.url
    dbname = f"alembic_outboxtext_{uuid.uuid4().hex[:8]}"
    admin_engine = create_engine(admin_url, isolation_level="AUTOCOMMIT")
    with admin_engine.connect() as conn:
        conn.execute(text(f'CREATE DATABASE "{dbname}"'))
    smoke_url = admin_url.set(database=dbname).render_as_string(hide_password=False)
    monkeypatch.setattr(app_config, "DATABASE_URL", smoke_url)
    cfg = Config(str(SERVER_DIR / "alembic.ini"))
    cfg.set_main_option("script_location", str(SERVER_DIR / "alembic"))
    engine = create_engine(smoke_url)
    columns_sql = text(
        "SELECT column_name FROM information_schema.columns"
        " WHERE table_name = 'notification_outbox' AND column_name IN ('title', 'body')"
    )
    try:
        command.upgrade(cfg, "c3e5a7b9d1f2")  # the down_revision
        with engine.begin() as conn:
            conn.execute(
                text(
                    "INSERT INTO users (id, username, hashed_password, is_admin)"
                    " VALUES (1, 'alice', 'x', false)"
                )
            )
            conn.execute(
                text(
                    "INSERT INTO notification (id, user_id, severity, category, event_type, title)"
                    " VALUES (1, 1, 'critical', 'monitoring', 'monitoring.check.transition',"
                    " 'Agents not reporting (3)')"
                )
            )
            conn.execute(
                text(
                    "INSERT INTO notification_outbox (id, notification_id, user_id, channel,"
                    " address, status, attempts)"
                    " VALUES (1, 1, 1, 'email', 'alice@example.test', 'pending', 0)"
                )
            )

        command.upgrade(cfg, "a7c9e1b3d5f2")
        with engine.begin() as conn:
            old = conn.execute(text("SELECT title, body FROM notification_outbox")).all()
            # id: (channel, status, last_error, sent_at), each with a text of its own
            for oid, channel, status, error, sent in (
                (2, "telegram", "pending", None, None),
                (3, "email", "sent", None, "2026-10-20 12:00:00"),
                (4, "email", "failed", "connection refused", None),
            ):
                conn.execute(
                    text(
                        "INSERT INTO notification_outbox (id, notification_id, user_id, channel,"
                        " address, status, attempts, last_error, sent_at, title, body)"
                        " VALUES (:id, 1, 1, :channel, 'alice@example.test', :status, 1,"
                        " :error, :sent, 'Agents not reporting (1)', '- db01')"
                    ),
                    {"id": oid, "channel": channel, "status": status, "error": error, "sent": sent},
                )
        assert [tuple(row) for row in old] == [(None, None)], "an older entry keeps no text"
        rows_sql = text(
            "SELECT id, status, last_error, attempts, sent_at FROM notification_outbox ORDER BY id"
        )
        with engine.connect() as conn:
            before = {row[0]: tuple(row) for row in conn.execute(rows_sql)}

        command.downgrade(cfg, "c3e5a7b9d1f2")
        with engine.connect() as conn:
            left = conn.execute(columns_sql).all()
            after = {row[0]: tuple(row) for row in conn.execute(rows_sql)}
        assert left == []
        assert sorted(after) == [1, 2, 3, 4], "the downgrade keeps every entry"
        assert after[2][1:3] == ("failed", "own text dropped by downgrade")
        assert after[2][3:] == before[2][3:], "attempts and sent_at stay"
        # Without a text of its own, already sent or already failed: untouched.
        assert after[1] == before[1] and after[1][1] == "pending"
        assert after[3] == before[3] and after[3][1] == "sent"
        assert after[4] == before[4] and after[4][2] == "connection refused"
    finally:
        engine.dispose()
        _drop_database(admin_engine, dbname)
        admin_engine.dispose()
